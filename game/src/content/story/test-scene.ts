      '(тест длинной реплики) Эта реплика нарочно длинная, чтобы проверить перенос строк, прокрутку и читаемость окна диалога на узком экране телефона и на широком мониторе. Если текст обрезается или выходит за пределы окна — это ошибка вёрстки.',
