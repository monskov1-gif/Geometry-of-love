// Эпилог и Концовка № 3 «За пределами экрана».
// Канон: Дамео приходит в себя перед своим компьютером; приложение закрыто, на
// рабочем столе только ярлык; он удаляет программу и возвращается к обычной
// жизни; в университете встречает Сацуки — она здоровается и проходит мимо;
// ничего не изменилось, она не влюбилась и не узнала, что он пережил; но он
// больше не считает её отказ доказательством своей никчёмности и понимает, что
// чужое внимание нельзя заслужить задачами, услугами или попытками стать
// незаменимым; позже открывает калькулятор на телефоне — крошечный радужный
// пиксель; голоса нет, приложение не открывается; неизвестно, осталось ли
// что-то от Калькулятора или это память о последней поездке.
// Развитие: звонок матери (в гл. 1 он не отвечал), старый тред на форуме,
// обещанный Ластику дождь. Выборов нет — эпилог читается до концовки.
