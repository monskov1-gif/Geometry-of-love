// Глава 15. «Радужный след».
// Канон: Калькулятор превращается в машинку с ярким радужным следом и
// предлагает запрыгнуть; последняя часть погони — он мчится через рушащийся
// мир на остатках сил; Мелоди пытается перекрыть дорогу, но пространство не
// подчиняется её командам; Дамео спрашивает, выберется ли Калькулятор; тот
// говорит, что всё рассчитал, потом признаётся, что не может покинуть игру —
// его файл слишком глубоко связан с системой; ускоряется и выталкивает Дамео к
// выходу; Дамео видит, как он исчезает вместе с миром; радужный след гаснет
// последним; Мелоди пытается остановить Дамео, мир окончательно разрушается.
// Развитие: шутка Циркулёнка «одолженная» Пушиным, отзывы флагов
// ch8.trusted-calculator и ch12.talk-later (прощание), последние слова Мелоди.
// После второй фазы погони выборов нет (e2e ожидает концовку).
import { background, branch, card, defineScene, episode, fx, goto, hide, label, narrate, say, sfx, show, space, think } from '../../../core/script';

export const chapter15 = defineScene({
  id: 'ch15',
  title: 'Глава 15. «Радужный след»',
  chapter: 15,
  steps: [
    space('code', 'E'),
    background('collapse'),
    card('Глава 15', '«Радужный след»', 'code', { backdrop: 'collapse' }),
    sfx('sparkle'),
    show('calculator', 'default', 'center'),
    narrate('Сбоку, из-за последнего куба, вылетает что-то маленькое и серое. Оно на ходу раскладывается: кнопки становятся колёсами, солнечная батарейка — фарой, экран — лобовым стеклом.'),
    narrate('Калькулятор превращается в небольшую машинку. Игрушечную, размером с табуретку. За ней тянется яркий радужный след — красный, оранжевый, жёлтый, зелёный, голубой, синий, фиолетовый, — единственное цветное, что осталось в этом мире.'),
    say('calculator', 'Запрыгивай! Быстрее! 8-D'),
    say('dameo', 'Пушин?! Ты… ты машинка!'),
    say('calculator', 'Я переназначил себе все настройки, какие остались. Скорость — максимум. Яркость — максимум. Размер — тесновато, конечно. Пристегнись. Ремней нет. Это шутка Циркулёнка, я её одолжил. Он бы не обиделся.'),
    hide('calculator'),
    episode('chase', { mode: 'car' }),
    background('collapse', undefined, 'end-car'),

    // ---- the last ride
    show('calculator', 'default', 'center'),
    narrate('Они мчатся через рушащийся мир. Калькулятор тратит оставшиеся силы — Дамео чувствует это по тому, как гудит корпус под ладонями, как мигает фара.'),
    narrate('Мелоди пытается перекрыть им дорогу: протягивает руку поперёк плоскости, ставит на пути куб, стену, дверь без ручки. Но пространство больше не подчиняется её командам. Куб рассыпается раньше, чем появляется. Стена проходит сквозь колёса, как туман.'),
    narrate('Впереди — выход. Прямоугольник света. Обратная сторона монитора, только не стеклянная — открытая.'),
    say('dameo', 'Пушин, а ты? Ты ведь тоже выберешься? Там хватит места на двоих. Ты маленький, ты пролезешь.'),
    say('calculator', 'Конечно. Я всё рассчитал. 8-)'),
    say('calculator', '…'),
    narrate('Цифры на лобовом стекле замирают. Потом медленно, по одной, гаснут.'),
    say('calculator', 'Нет. Я соврал. Это был последний раз, обещаю.'),
    say('calculator', 'Мой файл слишком глубоко связан с её системой. Я тут слишком долго. Я — её калькулятор. Я — её настройки. Если игры не станет, меня не станет тоже. Это не трагедия, Дамео. Это арифметика.'),
    say('calculator', 'Но ты — можешь. Твоя привязка снята. Ты чистый. Как новый лист.'),
    branch({ flag: 'ch8.trusted-calculator', is: false }, 'ch15#forgive'),
    say('calculator', 'Ты сказал, что доверяешь мне. Я подвёл тебя тогда. Пусть хотя бы последнее вычисление будет правильным.'),
    label('forgive'),
    branch({ flag: 'ch12.talk-later', is: false }, 'ch15#plain'),
    say('dameo', 'Мы же договорились. Поговорить, когда выберемся. Оба.'),
    say('calculator', 'Вот мы и говорим. Это и есть «когда выберемся». Просто выбирается один.'),
    say('dameo', 'Я тебя прощаю. Слышишь? Я тебя прощаю.'),
    say('calculator', 'Слышу. Я сохраню это в «M+». Там надёжно.'),
    goto('ch15#push'),
    label('plain'),
    say('dameo', 'Пушин…'),
    say('calculator', 'Не надо. Ты сказал, что не прощаешь. Это было честно. Мне хватит честного.'),
    label('push'),
    say('calculator', 'Держись. Сейчас будет быстро.'),
    sfx('rumble'),
    fx('shake'),
    narrate('Он ускоряется. Так, что радужный след за ними становится одной сплошной полосой. У самого края он резко тормозит — и Дамео вылетает вперёд, к выходу, как камешек из рогатки.'),
    hide('calculator'),
    think('dameo', 'Нет. Нет, подожди…'),
    narrate('Он успевает обернуться. Маленькая машинка стоит на краю плоскости, и мир вокруг неё складывается, как бумага. Куб. Шар. Линия. Точка.'),
    narrate('Калькулятор исчезает вместе с рушащимся миром. Радужный след гаснет последним — цвет за цветом, от фиолетового к красному, — и ещё секунду висит в темноте одна тонкая красная черта.'),
    show('melody', 'cheerful', 'center', 'distorted'),
    narrate('Из темноты к нему тянется рука — длинная, бесконечно длинная, с тёплыми пальцами.'),
    say('melody', 'Дамео, стой… Не уходи. Мне будет так тихо. Ты не представляешь, как тихо…'),
    say('melody', 'Мне нравится, когда ты остаёшься со мной подо…'),
    fx('fade-white'),
    hide('melody'),
    narrate('Игровой мир окончательно разрушается. Голос обрывается на середине слова. Как музыка в Песочнице. Как всё здесь.'),
    goto('epilogue'),
  ],
});
